// สมมุติว่าเรามี Variable ตั้งต้น 
// priceList ซึ่งบรรจุ Array ของตัวเลขราคาสินค้าแต่ละชิ้น เช่น [20, 30, 10, 40]
// totalPrice ซึ่งบรรจุตัวเลขยอดรวมราคาสินค้าทั้งหมด มีค่าตั้งต้นเป็น 0
// ให้เขียนโปรแกรมช่วยเพื่อนวางแผนในการช้อปปิ้งสินค้าในอาทิตย์นี้ 
// โดยที่ยอดรวมของราคาสินค้าทั้งหมดต้องอยู่ในงบ 100 บาท ตามนี้
// กรณีมากกว่า 100 ต้องแสดง “เงินไม่พอ น่าจะต้องช่วยร้านเค้าเก็บร้าน และทำความสะอาด 😰”
// กรณีน้อยกว่าหรือเท่ากับ 100 ต้องแสดง “โอเค มีเงินพอที่จะซื้อสินค้าเหล่านี้ได้ 😍”
const priceList =[20, 30, 10, 40];
let totalPrice = 0
for(let i = 0;i < 4;i++){
    totalPrice = totalPrice +priceList[i];
}
console.log(totalPrice);
if(totalPrice <=100){
    console.log("โอเค มีเงินพอที่จะซื้อสินค้าเหล่านี้ได้ 😍");
}else{
    console.log("เงินไม่พอ น่าจะต้องช่วยร้านเค้าเก็บร้าน และทำความสะอาด 😰");
}